function cellId(levelNumber: number, row: number, column: number) {
  return 'level-' + levelNumber + '-cell-' + row + '-' + column;
}

function createCells(
  levelNumber: number,
  values: MathValue[][],
  displayValues: Record<string, string> = {},
): NumberCell[] {
  return values.flatMap((row, rowIndex) =>
    row.map((value, columnIndex) => ({
      id: cellId(levelNumber, rowIndex, columnIndex),
      value,
      displayValue: displayValues[rowIndex + '-' + columnIndex],
      position: { row: rowIndex, column: columnIndex },
    })),
  );
}

function solution(
  levelNumber: number,
  positions: Array<[number, number]>,
  operators: Operator[],
) {
  return {
    cellIds: positions.map(([row, column]) =>
      cellId(levelNumber, row, column),
    ),
    operators,
  };
}

