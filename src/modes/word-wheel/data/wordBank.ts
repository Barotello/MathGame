function makeId(answer: string, index: number) {
  const slug = answer
    .toLocaleLowerCase('tr-TR')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ı/g, 'i')
    .replace(/ç/g, 'c')
    .replace(/ğ/g, 'g')
    .replace(/ö/g, 'o')
    .replace(/ş/g, 's')
    .replace(/ü/g, 'u');
  return `kelime-${index + 1}-${slug}`;
}

const generatedWords: WordEntry[] = additionalWords.map(
  ([answer, clue, category], index) => {
    const length = Array.from(answer).length;
    return {
      id: makeId(answer, index + threeLetterWords.length),
      answer,
      clue,
      category,
      difficulty: length <= 4 ? 1 : length <= 6 ? 2 : 3,
      enabled: true,
    };
  },
);

export const wordBank: WordEntry[] = [
  ...threeLetterWords,
  ...generatedWords.slice(0, 500 - threeLetterWords.length),
];
